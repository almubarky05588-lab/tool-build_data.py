/// أدوات عرض الأرقام والنصوص العربية في الواجهة.
library;

const _digits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];

/// يحوّل الأرقام اللاتينية إلى أرقام عربية مشرقية: 48 → ٤٨
String ar(Object n) {
  final s = n.toString();
  final b = StringBuffer();
  for (final c in s.codeUnits) {
    if (c >= 48 && c <= 57) {
      b.write(_digits[c - 48]);
    } else {
      b.writeCharCode(c);
    }
  }
  return b.toString();
}

/// «موضعان» / «٣ مواضع» / «١١ موضعًا» بحسب قواعد العدد.
String countPlaces(int n) {
  if (n == 1) return 'موضع واحد';
  if (n == 2) return 'موضعان';
  if (n >= 3 && n <= 10) return '${ar(n)} مواضع';
  return '${ar(n)} موضعًا';
}

